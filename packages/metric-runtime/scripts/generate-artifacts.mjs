function normalizeGeneratedText(value) {
  return `${value.replaceAll("\r\n", "\n").replaceAll("\r", "\n").trimEnd()}\n`;
}

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function isPlainRecord(value) {
  return (
    value !== null &&
    typeof value === "object" &&
    !Array.isArray(value) &&
    Object.getPrototypeOf(value) === Object.prototype
  );
}

function assertExactKeys(value, expected, label) {
  if (!isPlainRecord(value)) {
    throw new Error(`${label} must be a plain object`);
  }
  const actual = Object.keys(value).sort();
  const sortedExpected = [...expected].sort();
  if (
    actual.length !== sortedExpected.length ||
    actual.some((key, index) => key !== sortedExpected[index])
  ) {
    throw new Error(`${label} keys are invalid`);
  }
}

function decodeJsonSource(bytes, label) {
  if (
    bytes.length >= 3 &&
    bytes[0] === 0xef &&
    bytes[1] === 0xbb &&
    bytes[2] === 0xbf
  ) {
    throw new Error(`${label} must not contain a UTF-8 BOM`);
  }
  const text = new TextDecoder("utf-8", { fatal: true }).decode(bytes);
  if (text.includes("\r") || !text.endsWith("\n")) {
    throw new Error(`${label} must use LF and end with a newline`);
  }
  return text;
}

function assertOnlyLocalSchemaReferences(value, path = "#") {
  if (value === null || typeof value !== "object") return;
  if (Array.isArray(value)) {
    value.forEach((item, index) => assertOnlyLocalSchemaReferences(item, `${path}/${index}`));
    return;
  }
  if (Object.hasOwn(value, "$ref")) {
    if (typeof value.$ref !== "string" || !value.$ref.startsWith("#/")) {
      throw new Error(`External or invalid JSON Schema reference is forbidden at ${path}`);
    }
  }
  for (const [key, nested] of Object.entries(value)) {
    assertOnlyLocalSchemaReferences(nested, `${path}/${key}`);
  }
}

function assertPortableGeneratedText(label, value) {
  if (value.charCodeAt(0) === 0xfeff || value.includes("\r")) {
    throw new Error(`${label} must be UTF-8 LF text without a BOM`);
  }
  const nativePath = packageDirectory;
  const slashPath = packageDirectory.replaceAll("\\", "/");
  if (value.includes(nativePath) || value.includes(slashPath)) {
    throw new Error(`${label} must not contain an absolute workspace path`);
  }
}

function assertStandaloneIsSelfContained(source) {
  if (/\brequire\s*\(/u.test(source)) {
    throw new Error("Generated validator must not require Ajv runtime helpers");
  }
  if (/\bfrom\s+["']ajv\//u.test(source)) {
    throw new Error("Generated validator must not import Ajv runtime helpers");
  }
  if (/^\s*import\b/mu.test(source)) {
    throw new Error("Generated validator must not contain static imports");
  }
  if (/\beval\s*\(/u.test(source) || /\bnew\s+Function\b/u.test(source)) {
    throw new Error("Generated validator contains dynamic code execution");
  }
  if (/\bimport\s*\(/u.test(source)) {
    throw new Error("Generated validator contains dynamic import");
  }
}

async function generateDefinition(definition) {
  const schemaBytes = await readFile(definition.schemaPath);
  const schema = JSON.parse(decodeJsonSource(schemaBytes, definition.label));
  if (!isPlainRecord(schema) || schema.$id !== definition.schemaId) {
    throw new Error(`${definition.label} Schema identity is invalid`);
  }
  assertOnlyLocalSchemaReferences(schema);

  const generatedTypes = normalizeGeneratedText(
    await compile(
      { ...schema, title: definition.label },
      definition.label,
      {
        $refOptions: { resolve: { external: false } },
        additionalProperties: false,
        bannerComment: GENERATED_HEADER,
        cwd: packageDirectory,
        declareExternallyReferenced: true,
        format: true,
        ignoreMinAndMaxItems: false,
        strictIndexSignatures: true,
        style: {
          endOfLine: "lf",
          printWidth: 100,
          semi: true,
          singleQuote: false,
          tabWidth: 2,
          trailingComma: "all",
        },
        unknownAny: true,
      },
    ),
  );

  const ajv = new Ajv2020({
    allErrors: false,
    code: { esm: true, lines: true, source: true },
    strict: true,
    validateFormats: false,
  });
  const validate = ajv.compile(schema);
  const standalone = standaloneCode(ajv, validate);
  assertStandaloneIsSelfContained(standalone);
  const generatedValidator = normalizeGeneratedText(
    [
      "// @ts-nocheck -- Ajv standalone output is generated JavaScript compiled by tsc.",
      GENERATED_HEADER,
      standalone,
    ].join("\n"),
  );

  const artifacts = [
    {
      label: `${definition.label} generated types`,
      path: definition.generatedTypesPath,
      relativePath: definition.generatedTypesRelativePath,
      value: generatedTypes,
    },
    {
      label: `${definition.label} standalone validator`,
      path: definition.generatedValidatorPath,
      relativePath: definition.generatedValidatorRelativePath,
      value: generatedValidator,
    },
  ];
  artifacts.forEach((artifact) => assertPortableGeneratedText(artifact.label, artifact.value));

  return {
    definition,
    schemaBytes,
    schemaSha256: sha256(schemaBytes),
    artifacts,
  };
}

async function assertHistory(definitions) {
  const historyBytes = await readFile(historyPath);
  const history = JSON.parse(decodeJsonSource(historyBytes, "Metric Runtime history"));
  if (
    !isPlainRecord(history) ||
    history.schemaVersion !== "1.0.0" ||
    history.kind !== "datapulse-metric-runtime-contract-history" ||
    history.currentVersion !== "1.0.0" ||
    history.hashAlgorithm !== "SHA-256" ||
    !Array.isArray(history.versions) ||
    history.versions.length !== 1
  ) {
    throw new Error("Metric Runtime history identity is invalid");
  }
  assertExactKeys(
    history,
    ["schemaVersion", "kind", "currentVersion", "hashAlgorithm", "versions"],
    "Metric Runtime history",
  );
  const entry = history.versions[0];
  if (
    !isPlainRecord(entry) ||
    entry.version !== "1.0.0" ||
    entry.predecessor !== null ||
    entry.changeKind !== "initial"
  ) {
    throw new Error("Metric Runtime history version tuple is invalid");
  }
  assertExactKeys(
    entry,
    [
      "version",
      "predecessor",
      "changeKind",
      "accumulatorSchema",
      "evaluationPlanSchema",
      "runtimeSemantics",
    ],
    "Metric Runtime history entry",
  );

  const expectedByLabel = new Map([
    ["MetricAccumulator", entry.accumulatorSchema],
    ["MetricEvaluationPlan", entry.evaluationPlanSchema],
  ]);
  for (const generated of definitions) {
    const expected = expectedByLabel.get(generated.definition.label);
    assertExactKeys(
      expected,
      ["schemaId", "path", "bytes", "sha256"],
      `${generated.definition.label} history metadata`,
    );
    if (
      !isPlainRecord(expected) ||
      expected.schemaId !== generated.definition.schemaId ||
      expected.path !== generated.definition.schemaRelativePath ||
      expected.bytes !== generated.schemaBytes.length ||
      expected.sha256 !== generated.schemaSha256
    ) {
      throw new Error(`${generated.definition.label} history hash metadata is invalid`);
    }
  }

  const semantics = entry.runtimeSemantics;
  assertExactKeys(
    semantics,
    [
      "supportedAggregates",
      "interactionCapabilities",
      "sumWireEncoding",
      "negativeZero",
      "mergeOrder",
      "duplicateMergeOrdinal",
      "failurePriority",
      "emptyCountRows",
      "emptySum",
      "invalidInput",
      "finiteOverflow",
      "maxAccumulatorsPerEvaluation",
    ],
    "Metric Runtime history semantics",
  );
  if (
    !isPlainRecord(semantics) ||
    JSON.stringify(semantics.supportedAggregates) !== JSON.stringify(["COUNT_ROWS", "SUM"]) ||
    JSON.stringify(semantics.interactionCapabilities) !== JSON.stringify(["exact"]) ||
    semantics.sumWireEncoding !== "ieee754-binary64-big-endian-lowercase-hex" ||
    semantics.negativeZero !== "canonicalize-to-positive-zero" ||
    semantics.mergeOrder !== "mergeOrdinal-ascending" ||
    semantics.duplicateMergeOrdinal !== "reject" ||
    JSON.stringify(semantics.failurePriority) !==
      JSON.stringify([
        "accumulator-shape",
        "accumulator-version-invalid",
        "accumulator-version-unsupported",
        "metric-id-mismatch",
        "aggregate-mismatch",
        "merge-ordinal-duplicate",
      ]) ||
    semantics.emptyCountRows !== "zero" ||
    semantics.emptySum !== "unavailable" ||
    semantics.invalidInput !== "whole-evaluation-failure" ||
    semantics.finiteOverflow !== "unavailable" ||
    semantics.maxAccumulatorsPerEvaluation !== 65536
  ) {
    throw new Error("Metric Runtime history semantics are invalid");
  }
  return history;
}

function gitEnvironment() {
  const environment = { ...process.env };
  for (const key of [
    "GIT_DIR",
    "GIT_WORK_TREE",
    "GIT_INDEX_FILE",
    "GIT_OBJECT_DIRECTORY",
    "GIT_ALTERNATE_OBJECT_DIRECTORIES",
    "GIT_COMMON_DIR",
    "GIT_CEILING_DIRECTORIES",
    "GIT_DISCOVERY_ACROSS_FILESYSTEM",
  ]) {
    delete environment[key];
  }
  return environment;
}

function gitResult(args, encoding = "utf8") {
  return spawnSync("git", args, {
    cwd: repositoryRoot,
    encoding,
    env: gitEnvironment(),
    shell: false,
    windowsHide: true,
  });
}

function normalizeRepositoryPath(path) {
  const normalized = resolve(path);
  return process.platform === "win32" ? normalized.toLowerCase() : normalized;
}

function revisionExists(reference) {
  return gitResult(["rev-parse", "--verify", "--quiet", reference]).status === 0;
}

function parseRevisionList(output) {
  const revisions = output.split(/\r?\n/u).filter(Boolean);
  if (revisions.some((revision) => !GIT_OBJECT_ID_PATTERN.test(revision))) {
    throw new Error("Metric Runtime protected revision list is invalid");
  }
  return revisions;
}

function resolveTrustedBaselineRevisions() {
  const topLevel = gitResult(["rev-parse", "--show-toplevel"]);
  if (
    topLevel.status !== 0 ||
    normalizeRepositoryPath(topLevel.stdout.trim()) !== normalizeRepositoryPath(repositoryRoot)
  ) {
    throw new Error("Metric Runtime history repository root is unavailable");
  }

  const shallow = gitResult(["rev-parse", "--is-shallow-repository"]);
  if (shallow.status !== 0 || shallow.stdout.trim() !== "false") {
    throw new Error("Metric Runtime history requires a complete Git history");
  }

  const explicit = process.env.DATAPULSE_MERGE_BASE;
  if (explicit !== undefined && !GIT_OBJECT_ID_PATTERN.test(explicit)) {
    throw new Error("Metric Runtime merge-base override must be a full commit SHA");
  }
  const baseReference = explicit ??
    ["refs/remotes/origin/main", "refs/heads/main"].find(revisionExists);
  if (baseReference === undefined) {
    throw new Error("Metric Runtime trusted merge-base reference is unavailable");
  }

  const mergeBase = gitResult(["merge-base", "HEAD", baseReference]);
  const baselineRevision = mergeBase.stdout.trim();
  if (mergeBase.status !== 0 || !GIT_OBJECT_ID_PATTERN.test(baselineRevision)) {
    throw new Error("Metric Runtime merge-base resolution failed");
  }

  const head = gitResult(["rev-parse", "HEAD"]);
  const headRevision = head.stdout.trim();
  if (head.status !== 0 || !GIT_OBJECT_ID_PATTERN.test(headRevision)) {
    throw new Error("Metric Runtime HEAD revision is unavailable");
  }
  if (explicit !== undefined && baselineRevision === headRevision) {
    throw new Error("Metric Runtime merge-base override must not equal HEAD");
  }

  const protectedHistory = gitResult([
    "rev-list",
    "--full-history",
    "--topo-order",
    "--reverse",
    "HEAD",
    "--",
    protectedHistoryRepositoryPath,
  ]);
  if (protectedHistory.status !== 0) {
    throw new Error("Metric Runtime protected revision discovery failed");
  }
  return [
    ...new Set([baselineRevision, ...parseRevisionList(protectedHistory.stdout)]),
  ];
}

function canonicalJson(value) {
  if (Array.isArray(value)) {
    return value.map(canonicalJson);
  }
  if (!isPlainRecord(value)) {
    return value;
  }
  return Object.fromEntries(
    Object.keys(value)
      .sort()
      .map((key) => [key, canonicalJson(value[key])]),
  );
}

async function assertHistoryBaseline(currentHistory, revision) {
  const baselineManifest = gitResult(["show", `${revision}:${historyRepositoryPath}`]);
  if (baselineManifest.status !== 0) {
    const baselineFiles = gitResult([
      "ls-tree",
      "-r",
      "--name-only",
      revision,
      "--",
      protectedHistoryRepositoryPath,
    ]);
    if (baselineFiles.status !== 0 || baselineFiles.stdout.trim() !== "") {
      throw new Error("Metric Runtime baseline is missing its history manifest");
    }
    return;
  }

  let baselineHistory;
  try {
    baselineHistory = JSON.parse(baselineManifest.stdout);
  } catch {
    throw new Error("Metric Runtime baseline history is invalid JSON");
  }
  if (
    !isPlainRecord(baselineHistory) ||
    baselineHistory.schemaVersion !== currentHistory.schemaVersion ||
    baselineHistory.kind !== currentHistory.kind ||
    baselineHistory.hashAlgorithm !== currentHistory.hashAlgorithm ||
    !Array.isArray(baselineHistory.versions) ||
    baselineHistory.versions.length > currentHistory.versions.length
  ) {
    throw new Error("Metric Runtime history cannot be removed or replaced");
  }

  for (let index = 0; index < baselineHistory.versions.length; index += 1) {
    const baselineEntry = baselineHistory.versions[index];
    const currentEntry = currentHistory.versions[index];
    if (
      JSON.stringify(canonicalJson(baselineEntry)) !==
      JSON.stringify(canonicalJson(currentEntry))
    ) {
      throw new Error("Metric Runtime history entries are immutable and ordered");
    }
    for (const schemaMetadata of [
      baselineEntry?.accumulatorSchema,
      baselineEntry?.evaluationPlanSchema,
    ]) {
      if (!isPlainRecord(schemaMetadata) || typeof schemaMetadata.path !== "string") {
        throw new Error("Metric Runtime baseline schema metadata is invalid");
      }
      const repositorySchemaPath = `packages/metric-runtime/${schemaMetadata.path}`;
      const baselineSchema = gitResult(["show", `${revision}:${repositorySchemaPath}`], null);
      const currentSchema = await readFile(resolve(packageDirectory, schemaMetadata.path));
      if (
        baselineSchema.status !== 0 ||
        !Buffer.isBuffer(baselineSchema.stdout) ||
        !baselineSchema.stdout.equals(currentSchema)
      ) {
        throw new Error("Metric Runtime published schema bytes are immutable");
      }
    }
  }
}

async function assertHistoryAppendOnly(currentHistory) {
  for (const revision of resolveTrustedBaselineRevisions()) {
    await assertHistoryBaseline(currentHistory, revision);
  }
}

function generateHistoryMetadata(history) {
  const current = history.versions[history.versions.length - 1];
  const versions = history.versions.map((entry) => entry.version);
  return normalizeGeneratedText(
    [
      GENERATED_HEADER,
      `export const METRIC_RUNTIME_CURRENT_VERSION = ${JSON.stringify(history.currentVersion)} as const;`,
      `export const METRIC_RUNTIME_REGISTERED_VERSIONS = Object.freeze(${JSON.stringify(versions)} as const);`,
      `export const METRIC_RUNTIME_MAX_ACCUMULATORS_PER_EVALUATION = ${JSON.stringify(current.runtimeSemantics.maxAccumulatorsPerEvaluation)} as const;`,
    ].join("\n"),
  );
}

function stableFailureCode(error) {
  if (error instanceof SyntaxError) return "METRIC_RUNTIME_SCHEMA_JSON_INVALID";
  if (error instanceof TypeError) return "METRIC_RUNTIME_SCHEMA_UTF8_INVALID";
  const message = error instanceof Error ? error.message.toLowerCase() : "";
  if (
    message.includes("history") ||
    message.includes("baseline") ||
    message.includes("immutable") ||
    message.includes("merge-base")
  ) {
    return "METRIC_RUNTIME_HISTORY_INVALID";
  }
  if (message.includes("external")) return "METRIC_RUNTIME_SCHEMA_REFERENCE_FORBIDDEN";
  if (message.includes("runtime helpers") || message.includes("dynamic")) {
    return "METRIC_RUNTIME_GENERATED_CODE_UNSAFE";
  }
  if (message.includes("missing or stale")) return "METRIC_RUNTIME_GENERATED_ARTIFACT_STALE";
  return "METRIC_RUNTIME_GENERATION_FAILED";
}

async function main() {
  const mode = process.argv[2] ?? "--check";
  if (mode !== "--check" && mode !== "--write") {
    throw new Error("Expected --check or --write");
  }

  const generatedDefinitions = [];
  for (const definition of DEFINITIONS) {
    generatedDefinitions.push(await generateDefinition(definition));
  }
  const history = await assertHistory(generatedDefinitions);
  await assertHistoryAppendOnly(history);
  const generatedHistory = generateHistoryMetadata(history);
  assertPortableGeneratedText("Metric Runtime generated history", generatedHistory);
  const artifacts = [
    ...generatedDefinitions.flatMap((generated) => generated.artifacts),
    {
      label: "Metric Runtime generated history",
      path: generatedHistoryPath,
      relativePath: "src/generated/metric-runtime-history.generated.ts",
      value: generatedHistory,
    },
  ];
  const mismatches = [];

  if (mode === "--write") {
    await mkdir(generatedDirectory, { recursive: true });
  }
  for (const artifact of artifacts) {
    if (mode === "--write") {
      await writeFile(artifact.path, artifact.value, "utf8");
      continue;
    }
    let existing;
    try {
      existing = await readFile(artifact.path, "utf8");
    } catch {
      existing = null;
    }
    if (existing !== artifact.value) {
      mismatches.push(artifact.relativePath);
    }
  }

  const summary = {
    schemaVersion: "1.0.0",
    kind: "datapulse-generation-summary",
    check: "metric-runtime-generated-artifacts",
    mode: mode.slice(2),
    result: mismatches.length === 0 ? "passed" : "failed",
    platform: process.platform,
    architecture: process.arch,
    schemas: generatedDefinitions.map((generated) => ({
      version: generated.definition.version,
      schemaId: generated.definition.schemaId,
      source: generated.definition.schemaRelativePath,
      bytes: generated.schemaBytes.length,
      sha256: generated.schemaSha256,
    })),
    artifacts: artifacts.map((artifact) => ({
      path: artifact.relativePath,
      sha256: sha256(artifact.value),
    })),
    mismatches,
  };
  console.log(JSON.stringify(summary, null, 2));
  if (mismatches.length > 0) {
    throw new Error(`Generated artifacts are missing or stale: ${mismatches.join(", ")}`);
  }
}

try {
  await main();
} catch (error) {
  console.error(
    JSON.stringify(
      {
        schemaVersion: "1.0.0",
        kind: "datapulse-generation-failure",
        check: "metric-runtime-generated-artifacts",
        result: "failed",
        code: stableFailureCode(error),
      },
      null,
      2,
    ),
  );
  process.exitCode = 1;
}
